  State<ResultsScreen> createState() => _ResultsScreenState();
}

class _ResultsScreenState extends State<ResultsScreen> {
  // ==========================================
  // LOGIC: SHARE RESULTS
  // ==========================================
  void _shareResults() {
    String shareText = "🩸 *My BloodSense AI Report*\n\n";
    
    for (var marker in widget.evaluatedMarkers) {
      String name = marker["original_ocr_name"]?.toString() ?? "Marker";
      String value = marker["extracted_value"]?.toString() ?? "--";
      String unit = marker["unit"]?.toString() ?? "";
      String status = marker["status"]?.toString() ?? "Unknown";
      shareText += "• $name: $value $unit ($status)\n";
    }
    
    if (widget.healthRisks.isNotEmpty) {
      shareText += "\n⚠️ *Insights & Risks:*\n";
      for (var risk in widget.healthRisks) {
        shareText += "- ${risk['risk']}\n";
      }
    }
    
    shareText += "\nGenerated by BloodSense AI";
    Share.share(shareText, subject: 'My Blood Report Analysis');
  }

  // ==========================================
  // LOGIC: DOWNLOAD RESULTS
  // ==========================================
  Future<void> _downloadResults() async {
    try {
      final directory = await getApplicationDocumentsDirectory();
      final file = File('${directory.path}/BloodSense_Report_${DateTime.now().millisecondsSinceEpoch}.txt');

      String reportContent = "BLOODSENSE AI - CLINICAL REPORT\n";
      reportContent += "Date: ${DateTime.now().toString().split(' ')[0]}\n\n";
      reportContent += "MARKERS SUMMARY:\n";
      
      for (var marker in widget.evaluatedMarkers) {
        String name = marker["original_ocr_name"]?.toString() ?? "Marker";
        String value = marker["extracted_value"]?.toString() ?? "--";
        String unit = marker["unit"]?.toString() ?? "";
        String status = marker["status"]?.toString() ?? "Unknown";
        String low = marker["low"]?.toString() ?? "--";
        String high = marker["high"]?.toString() ?? "--";

        reportContent += "${name.toUpperCase()}\n";
        reportContent += "Result: $value $unit [$status]\n";
        reportContent += "Normal Range: $low - $high $unit\n\n";
      }

      await file.writeAsString(reportContent);

      if (!mounted) return;
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(
          content:  Text('✅ Report saved to device documents!'),
          backgroundColor: Colors.green.shade600,
          behavior: SnackBarBehavior.floating,
        ),
      );
    } catch (e) {
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(content: Text('Failed to save report: $e'), backgroundColor: Colors.red),
      );
    }
  }

  // ==========================================
  // UI HELPER: STATUS BADGE
  // ==========================================
  Widget _buildStatusBadge(String status) {
    Color bgColor;
    Color textColor;
    IconData icon;

    String s = status.toLowerCase();
    if (s.contains("high")) {
      bgColor =  Color(0xFFFEF0E6); 
      textColor =  Color(0xFFD97706); 
      icon = Icons.trending_up;
    } else if (s.contains("low")) {
      bgColor =  Color(0xFFFEE2E2); 
      textColor =  Color(0xFFDC2626); 
      icon = Icons.error_outline;
    } else {
      bgColor =  Color(0xFFE1FEEB); 
      textColor =  Color(0xFF10B981); 
      icon = Icons.check_circle_outline;
      status = "Normal";
    }

    return Container(
      padding:  EdgeInsets.symmetric(horizontal: 10, vertical: 4),
      decoration: BoxDecoration(color: bgColor, borderRadius: BorderRadius.circular(20)),
      child: Row(
        mainAxisSize: MainAxisSize.min,
        children: [
          Icon(icon, color: textColor, size: 14),
           SizedBox(width: 4),
          Text(status, style: TextStyle(color: textColor, fontSize: 12, fontWeight: FontWeight.bold)),
        ],
      ),
    );
  }

