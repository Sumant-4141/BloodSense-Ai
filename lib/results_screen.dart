  }

  // ==========================================
  // UI HELPER: INDIVIDUAL MARKER CARD (SAFE MATCHING)
  // ==========================================
  Widget _buildMarkerCard(Map<String, dynamic> marker) {
    String rawName = marker["original_ocr_name"]?.toString() ?? "Unknown";
    String status = marker["status"]?.toString() ?? "Unknown";
    bool isNormal = status.toLowerCase().contains("normal");
    
    String value = (marker["extracted_value"] ?? '--').toString();
    String minRange = (marker["low"] ?? '--').toString();
    String maxRange = (marker["high"] ?? '--').toString();
    String unit = (marker["unit"] ?? '').toString();

    String displayName = rawName;
    if (rawName.isNotEmpty) {
      if (rawName.length <= 4) {
        displayName = rawName.toUpperCase();
      } else {
        displayName = rawName[0].toUpperCase() + rawName.substring(1).toLowerCase();
      }
    }

    List<String> eatList = [];
    List<String> avoidList = [];
    List<String> exerciseList = [];
    String anomalyReason = "Anomaly detected. Review recommendations below.";

    if (!isNormal && widget.healthRisks.isNotEmpty) {
      Map<String, dynamic>? relatedRisk;
      
      String exactSearch = rawName.toLowerCase().trim();
      // ONLY remove safe formatting words, keep medical terms like "fasting"
      String fuzzySearch = exactSearch.replaceAll(" count", "").replaceAll(" level", "").trim();

      // TIER 1: Try to find an EXACT match first (e.g., "Glucose Fasting")
      for (var risk in widget.healthRisks) {
        String reasons = (risk["reasons"] as List?)?.join(" ").toLowerCase() ?? "";
        String riskTitle = risk["risk"]?.toString().toLowerCase() ?? "";
        
        if (reasons.contains(exactSearch) || riskTitle.contains(exactSearch) || exactSearch.contains(riskTitle)) {
          relatedRisk = risk;
          break;
        }
      }

      // TIER 2: If no exact match, try the fuzzy search (e.g., finding "Platelets" when UI says "Platelet count")
      if (relatedRisk == null) {
        for (var risk in widget.healthRisks) {
          String reasons = (risk["reasons"] as List?)?.join(" ").toLowerCase() ?? "";
          String riskTitle = risk["risk"]?.toString().toLowerCase() ?? "";
          
          if (reasons.contains(fuzzySearch) || riskTitle.contains(fuzzySearch) || fuzzySearch.contains(riskTitle)) {
            relatedRisk = risk;
            break;
          }
        }
      }

      // TIER 3: If still nothing, grab the first risk that has actual diet data to fall back on
      relatedRisk ??= widget.healthRisks.firstWhere(
        (risk) => risk["lifestyle"] != null, 
        orElse: () => widget.healthRisks.first
      );

      if (relatedRisk.isNotEmpty) {
        anomalyReason = relatedRisk["risk"]?.toString() ?? anomalyReason;
        var lifestyle = relatedRisk["lifestyle"];
        
        if (lifestyle != null) {
          eatList = (lifestyle["Foods_to_Add"] as List?)?.map((e) => e.toString()).toList() ?? [];
          avoidList = (lifestyle["Foods_to_Avoid"] as List?)?.map((e) => e.toString()).toList() ?? [];
          exerciseList = (lifestyle["Exercise_to_Add"] as List?)?.map((e) => e.toString()).toList() ?? [];
        }
      }
    }

    // THE ULTIMATE FALLBACK: If the CSV is completely empty for this marker
    if (!isNormal && eatList.isEmpty && avoidList.isEmpty) {
      eatList = ["Hydrate with plenty of water", "Fresh leafy green vegetables", "Lean proteins"];
      avoidList = ["Highly processed foods", "Excessive sodium/salt", "Refined sugars"];
      exerciseList = ["Light daily walking", "Consult a physician for tailored routines"];
    }

    return Container(
      margin: const EdgeInsets.only(bottom: 16),
      padding: const EdgeInsets.all(20),
      decoration: BoxDecoration(
        color: Colors.white,
        borderRadius: BorderRadius.circular(16),
        border: Border.all(color: Colors.grey.shade200, width: 1.5),
        boxShadow: [
          BoxShadow(color: Colors.black.withOpacity(0.02), blurRadius: 10, offset: const Offset(0, 4)),
        ],
      ),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          Row(
            mainAxisAlignment: MainAxisAlignment.spaceBetween,
            children: [
              Expanded(
                child: Text(
                  displayName,
                  style: const TextStyle(fontSize: 18, fontWeight: FontWeight.bold, color: Colors.black87),
                ),
              ),
              _buildStatusBadge(status),
            ],
          ),
          const SizedBox(height: 4),
          Text(
            "Normal: $minRange - $maxRange $unit",
            style: TextStyle(fontSize: 13, color: Colors.grey.shade500),
          ),
          const SizedBox(height: 16),
          Row(
            crossAxisAlignment: CrossAxisAlignment.baseline,
            textBaseline: TextBaseline.alphabetic,
            children: [
              Text(
                value,
                style: const TextStyle(fontSize: 32, fontWeight: FontWeight.w900, color: Colors.black),
              ),
              const SizedBox(width: 6),
              Text(
                unit,
                style: TextStyle(fontSize: 16, fontWeight: FontWeight.bold, color: Colors.grey.shade600),
              ),
            ],
          ),
          const SizedBox(height: 8),
          Text(
            isNormal ? "Within normal range" : anomalyReason,
            style: TextStyle(fontSize: 14, color: Colors.grey.shade700),
          ),
          
          if (!isNormal && (eatList.isNotEmpty || avoidList.isNotEmpty)) ...[
            const SizedBox(height: 16),
            Divider(color: Colors.grey.shade200),
            const SizedBox(height: 8),
            _buildRecommendationTile(
              title: "What to Eat", 
              icon: Icons.check, 
              iconColor: const Color(0xFF10B981), 
              items: eatList, 
            ),
            _buildRecommendationTile(
              title: "What to Avoid", 
              icon: Icons.close, 
              iconColor: const Color(0xFF64748B), 
              items: avoidList,
            ),
            _buildRecommendationTile(
              title: "Recommended Exercises", 
              icon: Icons.bolt, 
              iconColor: const Color(0xFFD97706), 
              items: exerciseList,
            ),
          ]
        ],
      ),
    );
  }

